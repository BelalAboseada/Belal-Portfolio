import { readFileSync, writeFileSync } from 'node:fs';

const src = readFileSync('public/belal-visual-identity/visual/01-logo/B-mark-950.svg', 'utf8');

const viewBox = src.match(/viewBox="([^"]+)"/)[1];
const transform = src.match(/<g transform="([^"]+)"/)[1];
const d = src.match(/<path d="([^"]+)"/)[1];

const out = `// AUTO-GENERATED by scripts/extract-mark.mjs — do not edit by hand.
// Source: public/belal-visual-identity/visual/01-logo/B-mark-950.svg (visual identity v2.0)
// The mark is a single evenodd path; it is always rendered in ONE flat colour.

export const B_MARK_VIEW_BOX = '${viewBox}';
export const B_MARK_TRANSFORM = '${transform}';
export const B_MARK_PATH =
  '${d}';
`;

writeFileSync('src/components/design/b-mark-path.ts', out);
console.log(`wrote src/components/design/b-mark-path.ts (path ${d.length} chars, viewBox ${viewBox})`);
